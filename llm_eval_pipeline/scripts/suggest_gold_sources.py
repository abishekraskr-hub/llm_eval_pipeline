"""Show what the app retrieves per question, to help write gold labels.

    python -m llm_eval_pipeline.scripts.suggest_gold_sources
    python -m llm_eval_pipeline.scripts.suggest_gold_sources --limit 5 --json

It NEVER writes gold labels. That is deliberate: if the labels came from what the
app already retrieves, the retrieval metrics would be scoring the app against its
own output and could never detect a regression. A human has to confirm that the
page really does contain the answer -- the labels are the ground truth, and ground
truth cannot be generated by the thing being measured.

What this does help with is the mechanical part: finding the candidates, and
showing which of your existing labels the app currently hits or misses.

Note this goes through the Target interface only (`ask`/`describe`), like every
other part of the platform -- it does not read the vector index directly, because
the platform must stay usable against an app it cannot import.
"""
import argparse
import json
import sys

from ..cli import build_target
from ..config import load_config, resolve
from ..dataset import DatasetError, load_dataset
from ..targets.base import TargetUnavailable


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="suggest_gold_sources",
        description="Print what the target retrieves per answerable question.",
    )
    parser.add_argument("--config", help="path to eval_config.yaml")
    parser.add_argument("--limit", type=int, help="only the first N answerable items")
    parser.add_argument("--tag", help="only items carrying this tag")
    parser.add_argument("--top", type=int, default=8, help="how many retrieved pages to show")
    parser.add_argument(
        "--json",
        action="store_true",
        dest="as_json",
        help="emit JSON you can edit into the dataset by hand",
    )
    args = parser.parse_args(argv)

    cfg = load_config(args.config)
    try:
        # Labels are what we are here to produce, so do not demand them up front.
        items = load_dataset(
            resolve(cfg["dataset"], cfg), tag=args.tag, require_gold_sources=False
        )
    except DatasetError as exc:
        print(f"dataset error: {exc}", file=sys.stderr)
        return 2

    answerable = [it for it in items if it.is_answerable]
    if args.limit:
        answerable = answerable[: args.limit]
    if not answerable:
        print("no answerable items to inspect", file=sys.stderr)
        return 2

    target = build_target(cfg)
    k = (cfg.get("retrieval") or {}).get("k", 5)
    out: list[dict] = []

    for index, item in enumerate(answerable, start=1):
        try:
            response = target.ask(item.question)
        except TargetUnavailable as exc:
            print(f"\ntarget unavailable at item {index}/{len(answerable)}: {exc}", file=sys.stderr)
            break

        retrieved = response.retrieved
        gold = set(item.gold_sources)
        suggestion = {
            "id": item.id,
            "question": item.question,
            "current_gold_sources": [{"file": f, "page": p} for f, p in item.gold_sources],
            "retrieved": [],
        }

        if retrieved is None:
            suggestion["retrieved"] = None
            suggestion["note"] = "target does not report what it retrieved"
        else:
            for hit in retrieved[: args.top]:
                suggestion["retrieved"].append(
                    {
                        "source_id": hit.source_id,
                        "page": hit.page,
                        "rank": hit.rank,
                        "in_current_gold": (hit.source_id, hit.page) in gold,
                        "within_k": hit.rank <= k,
                    }
                )
            found = {(h.source_id, h.page) for h in retrieved if h.rank <= k}
            suggestion["gold_missed_at_k"] = [
                {"file": f, "page": p} for (f, p) in sorted(gold - found)
            ]

        out.append(suggestion)

        if not args.as_json:
            print(f"\n=== {item.id}: {item.question}")
            if item.gold_sources:
                print(
                    "    current gold: "
                    + ", ".join(f"{f} p.{p}" for f, p in item.gold_sources)
                )
            else:
                print("    current gold: NONE -- needs labelling")
            if retrieved is None:
                print("    target does not report retrieval; cannot suggest pages")
                continue
            if not retrieved:
                print("    target retrieved nothing")
                continue
            for hit in retrieved[: args.top]:
                mark = "*" if (hit.source_id, hit.page) in gold else " "
                cut = "" if hit.rank <= k else f"  (below k={k})"
                print(f"    {mark} {hit.rank:>2}. {hit.source_id}{"" if hit.page is None else f" p.{hit.page}"}{cut}")
            missed = suggestion.get("gold_missed_at_k") or []
            if missed:
                print(
                    "    MISSED within k: "
                    + ", ".join(f"{m['file']} p.{m['page']}" for m in missed)
                )

    if args.as_json:
        print(json.dumps(out, indent=2))
    else:
        print(
            "\n* = already in gold_sources. Verify a page really answers the question "
            "before adding it; do not just copy what the app retrieved."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
